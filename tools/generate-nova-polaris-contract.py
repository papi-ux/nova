#!/usr/bin/env python3
"""Render Nova S1 names from the pinned, byte-identical Polaris schema/generator.

The canonical generator owns parsing, validation, consumers and C++ names. This
driver selects declared Nova reads and adds the Kotlin target; builds never run it.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import re
import sys

SCHEMA = 'shared/polaris/contract/polaris-v1-contract.json'
PROVENANCE = 'shared/polaris/contract/PROVENANCE.json'
GENERATOR = 'tools/generate-polaris-contract.py'
KOTLIN = 'shared/polaris/model/src/commonMain/kotlin/com/papi/nova/shared/polaris/contract/PolarisV1Contract.kt'
DECK = 'clients/deck/src/generated/polaris_v1_contract.h'


def digest(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()


def canonical_inputs(root: Path):
    raw_pin = (root / PROVENANCE).read_bytes()
    pin = json.loads(raw_pin)
    schema_bytes = (root / SCHEMA).read_bytes()
    generator_bytes = (root / GENERATOR).read_bytes()
    for name, raw, key in ((SCHEMA, schema_bytes, 'schema_sha256'),
                           (GENERATOR, generator_bytes, 'generator_sha256')):
        if digest(raw) != pin[key]:
            raise ValueError('provenance mismatch: ' + name)
    if not re.fullmatch(r'[a-f0-9]{40}', pin['upstream_commit']):
        raise ValueError('provenance needs a pinned upstream commit')
    # Verify the generator's bytes before importing it. Reuse its strict JSON
    # parser for the final provenance/schema read, including duplicate refusal.
    spec = importlib.util.spec_from_file_location('polaris_contract_canonical', root / GENERATOR)
    canonical = importlib.util.module_from_spec(spec)
    bytecode = sys.dont_write_bytecode
    try:
        sys.dont_write_bytecode = True
        spec.loader.exec_module(canonical)
    finally:
        sys.dont_write_bytecode = bytecode
    pin = canonical.load_schema(raw_pin)
    schema = canonical.load_schema(schema_bytes)
    return canonical, pin, schema, schema_bytes, generator_bytes


def selected_reads(canonical, schema: dict, kinds: set[str]) -> dict[str, set[str]]:
    selected = {}
    for name, obj in schema['objects'].items():
        if not obj.get('generated'):
            continue
        for kind, reader in canonical.consumers(obj):
            if kind in kinds:
                for field in reader['reads']:
                    if field in obj['fields']:
                        owner = canonical.owner_name(schema, name, field)
                        selected.setdefault(owner, set()).add(field)
    return selected


def render(root: Path, driver_bytes: bytes):
    canonical, pin, schema, schema_bytes, generator_bytes = canonical_inputs(root)
    # Canonical render performs schema validation and supplies exact C++ spelling.
    upstream = canonical.render(schema, schema_bytes, generator_bytes)
    cpp = upstream[canonical.CPP].decode()
    names = canonical.generated_values(cpp)
    header = ('// Generated by tools/generate-nova-polaris-contract.py; do not edit.\n'
              '// Polaris commit: ' + pin['upstream_commit'] + '\n'
              '// schema-sha256: ' + digest(schema_bytes) + '\n'
              '// generator-sha256: ' + digest(generator_bytes) + '\n'
              '// nova-driver-sha256: ' + digest(driver_bytes) + '\n')
    kotlin_reads = selected_reads(canonical, schema, {'nova_android', 'nova_shared'})
    deck_reads = selected_reads(canonical, schema, {'nova_deck'})
    kotlin = [header, '\npackage com.papi.nova.shared.polaris.contract\n\nobject PolarisV1 {\n']
    deck = [header, '#pragma once\n\n']
    kotlin_objects = set()
    for owner, obj in schema['objects'].items():
        if owner in kotlin_reads:
            symbol = ''.join(part.capitalize() for part in owner.split('_'))
            if symbol in kotlin_objects:
                raise ValueError('Kotlin object collision: ' + symbol)
            kotlin_objects.add(symbol)
            kotlin.append('    object ' + symbol + ' {\n')
            for field in obj['fields']:
                if field in kotlin_reads[owner]:
                    value = names['v1::' + owner + '::' + field]
                    kotlin.append('        const val ' + field.upper() + ' = ' + json.dumps(value) + '\n')
            kotlin.append('    }\n')
        if owner in deck_reads:
            opening = 'namespace polaris::contract::v1::' + owner + ' {\n'
            section = cpp.split(opening, 1)[1].split('}\n', 1)[0]
            deck.append(opening)
            for field in obj['fields']:
                if field in deck_reads[owner]:
                    value = names['v1::' + owner + '::' + field]
                    line = f'  inline constexpr char {field}[] = "{value}";\n'
                    start = section.index(line)
                    deck.append(section[start:start + len(line)])
            deck.append('}\n\n')
    kotlin.append('}\n')
    return canonical, {KOTLIN: ''.join(kotlin).encode(), DECK: ''.join(deck).encode()}


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parent.parent)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args(argv)
    try:
        canonical, outputs = render(args.root, Path(__file__).read_bytes())
        if not canonical.write_or_check(args.root, outputs, args.check):
            return 1
    except (OSError, ValueError, KeyError, TypeError, IndexError) as error:
        print('Nova contract generation refused: ' + str(error), file=sys.stderr)
        return 1
    print('Nova S1 contract names checked' if args.check else 'Nova S1 contract names generated')
    return 0


if __name__ == '__main__':
    sys.exit(main())
